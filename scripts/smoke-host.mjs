import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({channel:'msedge', headless:true});
const page = await browser.newPage();
page.on('pageerror', e => console.log('PAGEERROR',e.message));
page.on('console', e => { if(e.type()==='error')console.log('CONSOLE',e.text()); });
await page.goto(process.argv[2]); await page.waitForTimeout(3000);
console.log('TITLE',await page.title()); console.log((await page.locator('body').innerText()).slice(0,4500));
await mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/host-smoke.png'});
await browser.close();
