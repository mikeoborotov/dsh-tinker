import { build, version as esbuildVersion } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const icons = ['folder','code','terminal','server','database','network','cloud','cpu','bot','wrench','settings','shield','lock','key-round','home','briefcase','building-2','rocket','flask-conical','book-open','notebook','file-text','chart-no-axes-combined','wallet','calendar','mail','globe','layers','package','box','palette','image','music','video','coffee','star'];
const ru = ['Папка','Код','Терминал','Сервер','База данных','Сеть','Облако','Процессор','Агент','Инструменты','Настройки','Защита','Замок','Ключ','Дом','Работа','Компания','Ракета','Исследование','Книга','Блокнот','Документ','График','Финансы','Календарь','Почта','Интернет','Слои','Пакет','Коробка','Палитра','Изображение','Музыка','Видео','Кофе','Звезда'];

// All generated files belong to root. Dev packaging supplies an isolated source snapshot.
export async function buildClient({ root = projectRoot, moduleId = 'dsh-tinker' } = {}) {
  root = path.resolve(root);
  const lucideRoot = path.join(projectRoot, 'node_modules/lucide-static');
  const rows = await Promise.all(icons.map(async (id, i) => ({ id, ru: ru[i], en: id.replaceAll('-', ' '), svg: (await readFile(path.join(lucideRoot, 'icons', id + '.svg'), 'utf8')).replace(/<\?xml[^>]*>/g, '').replace(/<!--[^]*?-->/g, '').trim() })));
  await mkdir(path.join(root, 'src'), { recursive: true });
  await mkdir(path.join(root, 'dist'), { recursive: true });
  await writeFile(path.join(root, 'src/workspace-icons.json'), JSON.stringify(rows));
  const notice = (await readFile(path.join(root, 'THIRD_PARTY_NOTICES.md'), 'utf8')).replace(/\r\n/g, '\n');
  const split = notice.split('\n### Lucide license\n')[0];
  await writeFile(path.join(root, 'THIRD_PARTY_NOTICES.md'), split + '\n### Lucide license\n\n```text\n' + await readFile(path.join(lucideRoot, 'LICENSE'), 'utf8') + '\n```\n');
  await build({ absWorkingDir: root, entryPoints: ['src/client.jsx'], outfile: 'client.js', bundle: true, platform: 'browser', format: 'cjs', target: ['chrome120','safari17'], external: ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives'], minify: false,
    nodePaths: [path.join(projectRoot, 'node_modules')],
    banner: { js: '/* Generated by npm run build. Edit src/, not this file. */\nwindow.__ModuleLoader__.load({ id: ' + JSON.stringify(moduleId) + ', factory(require) {\nconst module = { exports: {} };' },
    footer: { js: '\nreturn module.exports;\n} });' } });
  return { icons: icons.length, esbuild: esbuildVersion };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildClient();
  console.log('Built client.js with ' + result.icons + ' icons; React and native Modal/Button are supplied by DSH.');
}
